std::size_t CountPixels(const Mask64& mask) {
  return static_cast<std::size_t>(std::count(mask.begin(), mask.end(), uint8_t{1}));
}

bool ValidMask(const Mask64& mask) {
  return std::all_of(mask.begin(), mask.end(), [](uint8_t value) { return value <= 1; }) &&
      CountPixels(mask) != 0;
}

bool TextMask(std::string_view text, Mask64* output) {
  std::array<const Glyph*, 5> glyphs{};
  std::size_t count = 0;
  for (std::size_t i = 0; i < text.size();) {
    if (count == glyphs.size()) return false;
    uint16_t code = static_cast<uint8_t>(text[i++]);
    if (code == 0xc2 && i < text.size() && static_cast<uint8_t>(text[i]) == 0xb0) {
      code = 176;
      ++i;
    } else if (code >= 128) return false;
    const auto* found = std::find_if(std::begin(kGlyphs), std::end(kGlyphs),
        [code](const Glyph& glyph) { return glyph.code == code; });
    if (found == std::end(kGlyphs)) return false;
    glyphs[count++] = found;
  }
  if (count == 0) return false;
  // Each glyph has five ink columns and one blank advance column.  Exclude
  // the trailing advance from the centered width so the visible text stays
  // centered while every pair of glyphs retains a full blank column.
  const int width = 6 * static_cast<int>(count) - 1;
  const int scale = std::min({4, 60 / width, 52 / 13});
  if (scale < 2) return false;
  const int left = (kSide - width * scale) / 2;
  const int top = (kSide - 13 * scale) / 2;
  Mask64 mask{};
  for (std::size_t glyph = 0; glyph < count; ++glyph) {
    for (int y = 0; y < 13; ++y) {
      for (int x = 0; x < 5; ++x) {
        if (glyphs[glyph]->rows[y] & (0x80 >> x))
          Block(&mask, left + (static_cast<int>(glyph) * 6 + x) * scale,
                top + y * scale, scale);
      }
    }
  }
  *output = mask;
  return true;
}

bool IconMask(std::string_view name, Mask64* output) {
  const std::array<uint16_t, 16>* icon = nullptr;
  if (name == "check") icon = &kCheck;
  else if (name == "warning") icon = &kWarning;
  else if (name == "pause") icon = &kPause;
  else return false;
  Mask64 mask{};
  for (int y = 0; y < 16; ++y)
    for (int x = 0; x < 16; ++x)
      if ((*icon)[y] & (0x8000 >> x)) Block(&mask, 8 + x * 3, 8 + y * 3, 3);
  *output = mask;
  return true;
}
